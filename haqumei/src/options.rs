use crate::utils::default_is_non_pause_symbol;

/// `Haqumei` の設定。
/// 詳細は、それぞれのフィールドのドキュメントを見てください。
#[derive(Debug, Clone, Copy)]
pub struct HaqumeiOptions {
    /// 入力テキストを [UnicodeNormalization] の指定された方法で正規化する。
    /// 「か + 濁点」などの結合文字を1文字の「が」に統合できます。
    ///
    /// デフォルトで無効になっています。
    pub normalize_unicode: UnicodeNormalization,

    /// この値が true の場合、発音表記 (`pron`) が文字表記 (`read`) によって上書きされます。
    ///
    /// これにより、長音の自動変換機能が無効化されます。 (e.g., "ジンセー" -> "ジンセイ")
    /// なお、助詞にもこの影響が及び、"は" は「ワ」ではなく「ハ」として、
    /// "へ" は「エ」ではなく「ヘ」として発音されます。
    ///
    /// すなわち、これを有効にした場合、`revert_long_vowels`, `revert_yotsugana` のフラグに関係なく、
    /// 読み (`read`) に強制的に置き換えられます。
    ///
    /// デフォルトで無効になっています。
    pub use_read_as_pron: bool,

    /// 辞書によって自動的に長音化された発音を、元のテキストに忠実な読みに復元するかどうか。
    ///
    /// `true` に設定すると、発音 (`pron`) に「ー」が含まれている単語について、
    /// 原形 (`orig`) に「ー」が含まれていない場合のみ、対応する読み (`read`) の母音に戻します。
    /// (e.g., 「効果」 pron: コーカ -> コウカ / 「人生」 pron: ジンセー -> ジンセイ)
    ///
    /// 同じ単語に含まれる助詞の発音、連濁、無声化記号は維持されます。
    ///
    /// デフォルトで無効になっています。
    pub revert_long_vowels: bool,

    /// 現代仮名遣いにおいて発音上統合される四つ仮名 (ヅ・ヂ) を、
    /// 元のテキスト通りの表記に復元するかどうか。
    ///
    /// `true` に設定すると、発音 (`pron`) において「ズ」「ジ」に変換されたものを、
    /// 読み (`read`) に基づいて「ヅ」「ヂ」に復元します。
    /// 長音、連濁、無声化記号など、四つ仮名以外の違いは維持されます。
    /// (e.g., 「気づかず」 pron: キズカズ -> キヅカズ / 「鼻血」 pron: ハナジ -> ハナヂ)
    ///
    /// デフォルトで無効になっています。
    pub revert_yotsugana: bool,

    /// 形態素解析辞書の仕様により「イウ」と「ユウ」のどちらに解析されるか不定な
    /// 動詞「言う」 (およびその活用形や複合語) の読み・発音を、指定した方に強制的に統一します。
    ///
    /// 辞書には「言う」に対して「イウ」「ユウ」の両方が登録されており、
    /// 形態素解析のコスト計算によって出力が変動します。
    /// `Some` を指定することで、解析結果に関わらず意図した発音に固定できます。
    ///
    /// デフォルトは `None` (形態素解析辞書の出力結果をそのまま使用する) です。
    pub normalize_iu: Option<IuPronunciation>,

    /// - フィラーが acc > mora_size のときに、平版型 (acc = 0) にする
    /// - フィラー直後の形態素が名詞だったとき、その前のフィラーに結合しない (chain_flag = 0) ようにする
    ///
    /// デフォルトで有効になっています。
    pub modify_filler_accent: bool,

    /// Nani Predictor を使って、「何」 の読みを修正する。
    ///
    /// デフォルトで有効になっています。
    pub predict_nani: bool,

    /// Kanalizer を使って、英語の読みを予測する。
    ///
    /// デフォルトで有効になっています。
    pub predict_kana_english: bool,

    /// 隣接する形態素で読みが決まる同形異音語を、語ごとの規則で補正する。
    ///
    ///   一見さん   -> イッケンさん から イチゲンさん へ
    ///   皆様方     -> ミナサマカタ から ミナサマガタ へ
    ///   兵どもが   -> ヘードモが   から ツワモノドモが へ
    ///
    /// 条件に合わないときは既定の読みのままです。
    /// (「一見して」は イッケンして のまま)
    ///
    /// デフォルトで有効になっています。
    pub modify_context_reading: bool,

    /// 旧国名 (令制国) に後続する接尾辞「国」の読みを「ノクニ」に補正する。
    ///
    ///   石見国 -> イワミコク から イワミノクニ へ
    ///   越後国 -> エチゴコク から エチゴノクニ へ
    ///
    /// 「中国」「外国」のように 1 形態素として解析される語は対象外です。
    ///
    /// デフォルトで有効になっています。
    pub modify_old_province_yomi: bool,

    /// 数詞まわりの読みを補正するかどうか
    ///
    /// - 分数の分母に来る「分」を `ブン` と読みます。
    ///   (`三分の一` -> `サンブンノイチ`)
    ///   時間量の `フン`/`プン` や割合の `ブ` は
    ///   後ろに「の + 数詞」が続かないので影響を受けません
    /// - 2 つ以上続く「〇」を伏字として `マル` と読みます。
    ///   (`〇〇株式会社` -> `マルマルカブシキガイシャ`)
    ///   単独の「〇円」は数詞のままです
    ///
    /// デフォルトで有効になっています。
    pub modify_numeral_reading: bool,

    /// 辞書が別の仮名に置き換えている外来語表記の仮名を、表層形から復元する。
    ///
    ///   ヴィクトリーヌ   ビクトリーヌ  から ヴィクトリーヌ へ
    ///   アイシュヴァルヤ アイシュバルヤ から アイシュヴァルヤ へ
    ///
    /// 音素の側は `ヴィ` `テュ` などを表現できるのに、辞書のエントリが
    /// バ行に置き換えているために出力できていません。これを表層形から戻します。
    ///
    /// 置き換えた形のほうが定着している語 (ホンジュラス / テイスト / バースデイ)
    /// は対象外です。
    ///
    /// 無効にすると Open JTalk と同じ出力になります。
    /// デフォルトで有効になっています。
    pub restore_loanword_kana: bool,

    /// ユーザー辞書が与えた読みを、後段の補正から守るかどうか
    ///
    /// 有効にすると、ユーザー辞書から引かれた形態素の `read` / `pron` /
    /// `mora_size` を保護します。
    ///
    /// ユーザー辞書に読みを書いても、後段の補正がそれを書き換えることがあります。
    /// このオプションは、書いた読みをそのまま残すためのものです。
    ///
    ///   ユーザー辞書に 十分,...,ジップン と書いた場合
    ///     無効: ジュウブン (文脈読みの補正が働く)
    ///     有効: ジップン
    ///
    /// 守るかどうかは表層形ではなく位置で決まり、ユーザー辞書から引かれた形態素と
    /// 重なる範囲だけが対象になります。そのため、同じ表層形が同じ文に現れても、
    /// システム辞書から引かれたほうは守られません。
    ///
    /// `use_read_as_pron` / `revert_long_vowels` / `revert_yotsugana` /
    /// `normalize_iu` は表記の慣習を選ぶオプションで、呼び出し側の明示的な
    /// 指定なので対象外です。アクセントも対象外です。
    ///
    /// デフォルトでは無効です。
    pub protect_user_dict_readings: bool,

    /// 辞書に無い漢字に、フォールバックの読みを与えるかどうか
    ///
    /// Open JTalk は読みを決められなかった語を「記号-読点」に格下げするため、
    /// `g2k` などでは辞書に無い漢字が表層形のままカナ列に混入する。
    /// (`騸馬` -> `騸馬`、`嗅神経` -> `嗅シンケー`)
    /// 辞書が単独で読める漢字は 約 3,100 字しかないので、それ以外はすべてこうなる。
    ///
    /// 有効にすると、そうした語に 1 文字ずつ読みを与える。
    /// (`騸馬` -> `センバ`)
    /// 1 字 1 読みの近似なので正しい読みになるとは限らないが、
    /// (`悪魔憑き` -> `アクマヒョウキ`) 漢字の混入は無くなる。
    ///
    /// 読みの出典とライセンスは `haqumei/data/unihan/README.md` を参照。
    ///
    /// 無効にすると pyopenjtalk と同じ挙動 (表層形をそのまま出力) になる。
    ///
    /// デフォルトで有効になっています。
    pub read_unknown_kanji: bool,

    /// 一部の漢語接頭辞 (本, 当, 同, 全) のあとでアクセント句を切る。
    ///
    ///   本論文 → ホ\]ン | ロンブン,  当ホテル → ト\]ー | ホテル
    ///
    /// これらの接頭辞は後続語と融合せず、別のアクセント句として現れます。
    ///
    /// 無効にすると Open JTalk と同じ挙動 (接頭辞と後続語を同じアクセント句に
    /// まとめる) になり、接頭辞のアクセント核が句全体を支配します。
    ///
    /// デフォルトで有効になっています。
    pub split_prefix_accent_phrase: bool,

    /// 長母音、重母音、撥音がアクセント核に来た場合に、
    /// ひとつ前のモーラにアクセント核がズレるルールを適用する。
    ///
    /// デフォルトで有効になっています。
    pub retreat_acc_nuc: bool,

    /// 品詞「特殊・マス」の直前に接続する動詞にアクセント核がある場合、アクセント核を「ま」に移動させる。
    ///
    ///   書きます -> か\[きま\]す, 参ります -> ま\[いりま\]す
    ///   書いております -> \[か\]いております
    ///
    /// デフォルトで有効になっています。
    pub modify_acc_after_chaining: bool,

    /// 踊り字 (e.g., 々, ヽ, ヾ) の展開を有効にする。
    ///
    /// デフォルトで有効になっています。
    pub process_odoriji: bool,

    /// `*_detailed` API において、記号に対して `pau` を割り当てるべきか判定する関数を設定するフィールド。
    ///
    /// `true` を返した記号には `pau` が付与されません。
    /// 閉じ括弧に `pau` を割り当てたくないようなケースに使ってください。
    ///
    /// デフォルトでは、以下の表層形に `pau` が割り当てられません。
    /// `「` , `」` , `『` , `』` , ` (` , `) ` , `(` , `)` ,
    /// `【` , `】` , `［` , `］` , `[` , `]` , `〈` , `〉` ,
    /// `《` , `》` , `〔` , `〕` , `｛` , `｝` , `{` , `}` ,
    /// `"` , `'` , `”` , `“` , `’` , `‘`
    ///
    /// # Examples
    ///
    /// ```rust
    /// use haqumei::utils::default_is_non_pause_symbol;
    ///
    /// fn my_custom_pause_rule(s: &str) -> bool {
    ///     if s == "「" {
    ///         return false; // false を返すと pau が割り当てられる
    ///     }
    ///     // それ以外はデフォルトの挙動を継承
    ///     default_is_non_pause_symbol(s)
    /// }
    /// ```
    pub is_non_pause_symbol: fn(&str) -> bool,

    /// 撥音・促音の代表的な異音分類をまとめて有効化します。
    /// 実測による記述に加え、発話末促音の `ClQ` など表記上の約束も含みます。
    ///
    /// 以下のオプションが強制的に有効化されます。
    /// - `split_n_allophones = true`
    /// - `split_q_allophones = true`
    /// - `enable_final_glottal_stop = true`
    ///   (Fujimoto, Maekawa & Funatsu (2010) は語中促音を調べた研究であり、
    ///   発話末の声門閉鎖を直接裏付けるものではありません。
    ///   [`Self::enable_final_glottal_stop`] に研究の範囲と実装上の扱いを記載しています)
    ///
    /// これが `true` である時点で、上記 3 つのオプションは強制的に上書きされることに
    /// 注意してください。
    ///
    /// 以下のオプションは自動では有効化せず、個別の設定値を使います。
    /// 参照した研究だけでは細分化の直接的な裏付けが十分でない可能性があるため、
    /// 既定では無効としています。根拠と留保は各オプションの説明を参照してください。
    /// - [`Self::split_n_before_r`]
    /// - [`Self::split_n_before_palatal_affricate`]
    ///
    /// デフォルトで無効になっています。
    pub use_allophones: bool,

    /// 撥音「ン」を後続音素の環境に応じて異音 (allophone) に分岐させるかどうか。
    /// false かつ `use_allophones == false` の場合は `Nn` (`"N"`) のみを出力します。
    ///
    /// # 詳細
    /// 有効にした場合、後続音素の調音部位に応じて以下の音素に解決されます：
    /// - 両唇音 (p, b, m) の前: `Nm` `[m]`
    ///   (例：サンマ -> s a `[Nm]` m a / テンプラ -> t e `[Nm]` p u r a)
    /// - 軟口蓋音 (k, g) の前: `Ng` `[ŋ]`
    ///   (例：サンカ -> s a `[Ng]` k a / マンガ -> m a `[Ng]` g a)
    /// - 発話境界の前: `Nq` `[ɴ]`
    ///   (例：ホン -> h o `[Nq]`)
    /// - 上記以外の破裂・破擦・鼻・流音 (t, d, ts, n, z, および任意で ch, j, r) の前: `Nd` `[n]`
    ///   (例：サンタ -> s a `[Nd]` t a / カンジ -> k a `[Nd]` j i)
    ///
    /// 母音、半母音 (y, w)、無声摩擦音 (s, sh, h, f)、有声摩擦音 (v) の前では、
    /// 分岐せず `Nn` を出力します。`Nn` は実現を特定しないラベルであり、
    /// 口腔閉鎖を伴う鼻音と鼻音化母音の両方を含みうるものです。
    ///
    /// # 摩擦音・半母音の前をさらにオプション化していない理由
    ///
    /// Maekawa (2023, JIPA 53(1): 189–212, Table 1) では、語中撥音が
    /// 閉鎖を伴った例は `[s]` の前で35/40例、`[j]` (半母音 y) の前で25/33例、
    /// `[ç]` (「ヒ」などの子音) の前で6/11例でした。対象語と話者を限定した
    /// 件数ですが、これらの環境で鼻音化母音が大多数だとはいえません。
    /// 一方、同論文の §3.1 では `[h]`・`[ɸ]`・`[w]` の前の撥音は
    /// 主に鼻音化母音だったため、閉鎖位置の分析から除いたと説明しています。
    ///
    /// 同じ後続子音でも口腔閉鎖の有無が変わるため、後続音素だけから
    /// 一つの実現を全例に割り当てる規則には留保が必要です。
    /// 話速や発話様式が変異をどの程度説明するかも、この分析だけでは決まりません。
    /// 鼻音化母音または鼻音閉鎖を一律に強制するフラグは設けず、
    /// `Nn` を音響モデルへ渡す設計にしています。
    ///
    /// なお、Maekawa (2023) 自身も結論部において、語末 /N/ の変異を
    /// "直前母音によって調音位置を書き換える離散的な異音規則" として説明
    /// するべきではないと明言しており (/N/ の調音位置の分布が相当に重なり
    /// 合っているため)、本ライブラリの設計判断と一致しています。さらに、
    /// 同論文の統計分析 (反復対比による GLMM検定) では、隣接する母音水準
    /// のうち i-e 間および u-a 間には有意差がある一方、e-u 間および a-o 間
    /// には有意差が見られませんでした。つまり統計的に意味のある区分は、
    /// 前舌 (i, e) / 後舌 (u, a, o) という伝統的な2分法ではなく、
    /// 「{i} / {e, u} / {a, o}」という3水準のグルーピングに近いことを
    /// 示しています。ただし、有意差がないことは調音点の同一性の証明ではなく、
    /// 個々の発音を3種類の固定された異音に分ける規則でもありません。
    ///
    /// # 設計上の注意 (チ前 / r前の統合について)
    ///
    /// Vance (2008) などには、r の前の撥音の舌先による構えや、
    /// チ・ジの前の歯茎硬口蓋鼻音を、他の歯茎音の前から区別する記述があります。
    /// Maekawa (2023, JIPA, §3.1・§4.1) は r と ch (`[tɕ]`) を
    /// t, d, ts, n, z などと同じ Alveolar 群に分類していますが、
    /// これは後続子音に基づいて分析前に設定した分類です。
    /// r/ch と他の歯茎音の違いを個別に検定した結果ではないため、
    /// この分類だけでは細分化を支持するとも、調音点の差がないともいえません。
    ///
    /// 細分化を一律に適用する規則の学術的な裏付けは十分でない可能性があるため、
    /// 本ライブラリでは既定で `Nd` にまとめています。`Nd` への統合も
    /// 調音点の同一性が実証された規則ではなく、分類を粗く保つための選択です。
    /// (`split_n_before_r` / `split_n_before_palatal_affricate` で個別に分離可能)
    ///
    /// なお j (`[dʑ]`) については、同論文の当該分類に明示的な記載が
    /// なく、Alveolarへの統合を直接支持する実測根拠は確認できていません。
    /// 分離時に ch と同じ `Npl` を共有させているのは、音韻的な対応関係 (チ・
    /// ジが共に同じ口蓋化の系列をなすという伝統的扱い) に基づく簡略化で
    /// あり、jについてはこの章で述べたrtMRIの直接的裏付けがない点に注意
    /// してください。
    ///
    /// また、語末の `Nq` を直前母音の前後性によって離散的に二値化する規則
    /// も、実際には連続的な調音位置の変動であることが示されているため、
    /// 本オプションでは単一の `Nq` として出力します。
    ///
    /// デフォルトで無効になっています。
    pub split_n_allophones: bool,

    /// `split_n_allophones` または `use_allophones` が有効なとき、r/ry の前の撥音を、
    /// `Nd` から専用ラベル `Nr` に分けて出力するかどうか。
    /// false の場合は r/ry の前も `Nd` に統合されます。
    /// 両方とも無効なときは無視されます。(`Nn` のまま)
    ///
    /// [`crate::Haqumei::g2ipa`] では、本設定の値にかかわらず
    /// r/ry の前の撥音を `[n]` と表記します。
    ///
    /// # 詳細
    ///
    /// 有効にした場合：
    /// - r, ry の前: `Nr`
    ///   (例：サンライ -> s a `[Nr]` r a i)
    ///
    /// 無効 (デフォルト) の場合：
    /// - r, ry の前: `Nd` `[n]`
    ///   (例：サンライ -> s a `[Nd]` r a i)
    ///
    /// # `Nr` が分離されている理由
    ///
    /// r の前の撥音を t/d/n の前と区別する記述があるため、`Nr` を設けています。
    ///
    /// Vance (2008: 97) は、r の前の撥音を尖端歯茎鼻音 `[n̺]` としています。
    /// t/d/n の前では舌面で閉鎖するのに対し、r の前では舌先を使うという区別です。
    /// 舌のどの部分を使うかの違いであって、閉鎖位置が後ろにずれるという意味ではありません。
    /// 一方、Okada (1999) は r 自体を後部歯茎音と記述しています。
    /// r に先行する撥音も同じ位置で閉鎖すると仮定すれば `[n̠]` と表記できますが、
    /// r の記述だけでは、撥音まで後部歯茎鼻音になることを裏付けられません。
    ///
    /// さらに、r が後部歯茎音であるという前提にも、実測結果との食い違いがあります。
    /// Maekawa (2023, ICPhS) が調べた男性話者7名の r、167例は、すべて歯茎域の
    /// tap で、後部歯茎の flap は観測されず、閉鎖位置は隣接母音によって変わりました。
    /// ただし、調べたのは語頭・母音間の r であり、r の前の撥音は対象外です。
    ///
    /// 撥音を調べた Maekawa (2023, JIPA 53(1): 189–212) でも、
    /// r の前の撥音と t/d/n の前の撥音の違いは個別に検定されていません。
    /// r は他の歯茎音とともに Alveolar 群に分類されていますが、後続子音の分類であり、
    /// r の前と t/d/n の前で撥音の閉鎖位置が同じだったという結果ではありません。
    ///
    /// r の前の撥音を一律に `[n̠]` とするには学術的な根拠が弱い可能性があるため、
    /// `split_n_before_r` は既定で無効にしています。
    /// 後部歯茎鼻音として表記する用途や、r の前の撥音を別のラベルで音響モデルに
    /// 学習させる用途のため、`Nr` に分けて出力できるようにしています。
    ///
    /// デフォルトで無効になっています。
    pub split_n_before_r: bool,

    /// `split_n_allophones` または `use_allophones` が有効なとき、ch, j の前の撥音を、
    /// `Nd` (`[n]`) からさらに分離して専用の `Npl` `[ɲ]` (硬口蓋鼻音) として
    /// 出力するかどうか。false の場合は ch, j の前も `Nd` に統合されます。
    /// 両方とも無効なときは無視されます。(`Nn` のまま)
    ///
    /// # 詳細
    ///
    /// 有効にした場合：
    /// - ch, j の前: `Npl` `[ɲ]`
    ///   (例：サンチョウ -> s a `[Npl]` ch o u / カンジ -> k a `[Npl]` j i)
    ///
    /// 無効 (デフォルト) の場合：
    /// - ch, j の前: `Nd` `[n]`
    ///   (例：サンチョウ -> s a `[Nd]` ch o u / カンジ -> k a `[Nd]` j i)
    ///
    /// # `Npl` が分離されている理由
    ///
    /// チ・ジ (`[tɕ]`, `[dʑ]`) の前の撥音を歯茎硬口蓋鼻音として
    /// 他の歯茎音の前から区別する記述があります。
    /// Vance (2008: 96–97) は歯茎硬口蓋の閉鎖を持つ鼻音として扱っています。
    /// 本ライブラリでは、狭い表記の細部を省いた代表記号 `[ɲ]` を使います。
    ///
    /// Maekawa (2023, JIPA, §3.1・§4.1) の rtMRI 分析では、
    /// ch (`[tɕ]`) は他の歯茎音と同じ Alveolar 群に含まれます。
    /// ただし、群内で ch 前の閉鎖位置を他の歯茎音の前と比較した検定ではなく、
    /// 「物理的に異なる閉鎖位置が観測されなかった」という結論にはなりません。
    /// j (`[dʑ]`) は当該分類に明示されておらず、この研究から直接の
    /// 裏付けを得ることもできません。ch と同じ `Npl` を返す処理は、
    /// チ・ジの音韻的な対応関係に基づく簡略化を含みます。
    ///
    /// 参照した研究だけでは細分化の直接的な裏付けが十分でない可能性があるため、
    /// 既定では無効としています。一方、歯茎硬口蓋鼻音を区別する記述との
    /// 対応が必要な用途もあるため、`Npl` への分離を選択できるようにしています。
    /// 既定の `Nd` への統合も、調音点の差がないという実測上の結論ではありません。
    ///
    /// デフォルトで無効になっています。
    pub split_n_before_palatal_affricate: bool,

    /// 語中における促音「ッ」を、後続子音の性質に応じて専用の異音
    /// (`ClP`/`ClT`/`ClK`/`ClS`/`ClV`) に分岐させるかどうか。
    /// (語末・感嘆表現の「ッ」は対象外です。[HaqumeiOptions::enable_final_glottal_stop] を参照してください)
    /// false かつ `use_allophones == false` の場合は `Cl` のみを出力します。
    ///
    /// # 詳細
    ///
    /// 有効にした場合、以下の音素に解決されます：
    /// - 無声破裂音・破擦音の前: `ClP` (p前), `ClT` (t, ts, ch前), `ClK` (k前)
    ///   - 無音の閉鎖区間として発音される
    ///     (例：キップ -> k i `[clp]` p u / キッテ -> k i `[clt]` t e / ガッコウ -> g a `[clk]` k o o)
    /// - 摩擦が継続する音 (s, sh, f, h、および有声摩擦音 v) の前: `ClS`
    ///   - 無音ではなく摩擦エネルギーが1モーラ分継続する
    ///     (例：ハッサイ -> h a `[cls]` s a i / ザッシ -> z a `[cls]` sh i)
    /// - 有声閉鎖・破擦音 (b, d, g, z, j) の前: `ClV`
    ///   - 音韻的な有声性を表し、閉鎖中の部分的な無声化を含む
    ///     主に外来語や和語の強調形 (「すごい→すっごい」等) に現れる
    ///     (例：バッグ -> b a `[clv]` g u / ベッド -> b e `[clv]` d o)
    ///
    /// Kawahara (2005: 93–95) の被験者3名では、有声促音の声帯振動は
    /// 閉鎖区間の約30–40%にとどまりました。`ClV` は音韻的な分類であり、
    /// 閉鎖全体の声帯振動を保証するラベルではありません。
    ///
    /// # `v` の分類について
    ///
    /// 有声摩擦音 `v` は、`ClV` (有声閉鎖) ではなく `ClS`
    /// (摩擦継続) に分類しています。促音が「無音区間になるか、音響エネルギー
    /// が継続するか」を決めるのは声帯振動の有無ではなく、閉鎖か摩擦かで
    /// 判断するべきだとしているからです。
    /// `ClV` という名称が示す「閉鎖」を、そもそも口腔閉鎖を持たない
    /// `v` の分類名に使うのは整合しません。
    ///
    /// `z` の促音には `[oddzɯ]` のような破擦音の記述があるため、
    /// 閉鎖を持つ阻害音として `ClV` を採用しています。
    /// Kawahara (2015: 54, 注13) は破擦化を可能性として述べており、
    /// すべての発音に必須の実現として保証しているわけではありません。
    ///
    /// 「ッヴ」自体の構音を検証した規則ではありません。
    /// `v` を `ClS` に含めるのは分類の一貫性を優先したものであり、
    /// 参照した文献による直接の実証的な裏付けはありません。
    ///
    /// デフォルトで無効になっています。
    pub split_q_allophones: bool,

    /// 発話境界の前の促音「ッ」 (「あっ！」「うっ」等) を、
    /// 専用の声門閉鎖音ラベル `ClQ` `[ʔ]` として出力するかどうか。
    /// false かつ `use_allophones == false` の場合は `Cl` のままです。
    /// `split_q_allophones` の値とは独立に動作します。
    ///
    /// # 詳細
    ///
    /// 発話末の「ッ」には後続子音がないため、語中促音のように後続子音から
    /// 閉鎖や摩擦の種類を割り当てることができません。
    /// 発話末を専用ラベルで音響モデルに渡す用途のため、独立したオプションを
    /// 設けています。声門閉鎖の有無や長さを音声から検出する処理ではありません。
    ///
    /// `ClQ` は声門閉鎖 `[ʔ]` を表す約束ですが、実際の発話がすべて
    /// 離散的な無音区間と声門破裂を持つと保証するものではありません。
    ///
    /// # 語中促音の実測と、発話末への適用の限界
    ///
    /// 高速度デジタルビデオ撮影と光電声門図 (PGG) を用いた
    /// Fujimoto, Maekawa & Funatsu (2010, INTERSPEECH) の観測
    /// (東京方言の男性話者1名による予備的研究) により、後続に阻害音がある通常の語中
    /// 促音 (ジェミネート) の発音中には、声門の明確な収縮・緊張は見られない
    /// ことが報告されています。(むしろ促音全般において、対応する単音より
    /// わずかに声門が広く開く傾向が観測されており、これは声門化とは逆方向の現象です)
    ///
    /// なお、閉鎖音や破擦音の促音においては、声門の開閉そのものには収縮が見られない
    /// ものの、光電声門図で「開大の軌跡に中断が生じる」「直前母音の声帯振動がより速く
    /// 停止する」という微細な差異が検出されています。これは口腔内の閉鎖動作の
    /// 速さ・強さの違いを反映している可能性が指摘されています。
    /// (なお、この中断現象は摩擦音が後続する促音では観測されていません)
    ///
    /// ただし、同研究の対象は被験者1名の語中促音であり、発話末の「ッ」は
    /// 調べていません。著者らも話者を増やした追加検証が必要だとしています。
    /// 語中で声門の緊縮を観測しなかったことから、発話末では必ず声門閉鎖に
    /// なると結論することはできません。
    ///
    /// したがって、発話末を一律に `[ʔ]` へ変換する規則の直接的な裏付けは、
    /// Fujimoto et al. (2010) だけでは得られません。`ClQ` は発話末を
    /// 区別するための表記上の約束として提供しており、実測で確定した分類と
    /// 同じ確実性を持つものではありません。
    ///
    /// デフォルトで無効になっています。
    pub enable_final_glottal_stop: bool,
}

